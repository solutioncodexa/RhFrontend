export function translate(lang: Lang, text: string): string {
  if (lang !== "ar" || text == null) return text;
  const raw = String(text);
  const key = raw.trim();
  if (!key) return raw;
  const known = phrases[key];
  if (known) return raw.startsWith(" ") || raw.endsWith(" ") ? `${raw.startsWith(" ") ? " " : ""}${known}${raw.endsWith(" ") ? " " : ""}` : known;
  const bonjour = key.match(/^Bonjour\s+(.+)$/);
  if (bonjour) return `مرحباً ${bonjour[1]}`;
  const bulletin = key.match(/^Bulletin — (.+)$/);
  if (bulletin) return `كشف — ${bulletin[1]}`;
  const droits = key.match(/^Droits — (.+)$/);
  if (droits) return `الصلاحيات — ${droits[1]}`;
  const absent = key.match(/^(\d+) absent(s)? aujourd’hui$/);
  if (absent) return `${absent[1]} غائب اليوم`;
  const leave = key.match(/^(\d+) en congé$/);
  if (leave) return `${leave[1]} في عطلة`;
  const actifs = key.match(/^(\d+) actifs?$/);
  if (actifs) return `${actifs[1]} نشط`;
  return raw;
}
